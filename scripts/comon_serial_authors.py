"""comon_serial_authors.py — кто такой «серийный автор»: порог, выведенный из данных.

Шаг 2а плана переделки раздела 4.5.

ЗАЧЕМ. Нынешний раздел 4.5 отбирает пятёрку по признаку «больше 20 стратегий прошли
фильтр измеримости». Отсечка назначена вручную, и — хуже — содержит исход внутри
критерия: измеримость означает дожитие до 100 торговых дней, то есть авторы отобраны
по живучести, а дальше раздел меряет у них живучесть. Здесь отсечка ищется по данным
и ТОЛЬКО по числу СОЗДАННЫХ стратегий: создание — это поведение автора, а не результат.

Что печатается:
  А. Распределение числа созданных стратегий на автора: перцентили, хвост поштучно.
  Б. Есть ли естественный разрыв — ищем скачок в упорядоченном ряду k.
  В. Таблица порогов-кандидатов (5, 10, 11, 15, 20, 22, 25, 30): сколько авторов и
     систем остаётся, какая доля популяции, хватает ли для кластеризации.
  Г. Устойчивость выбора: как меняется состав группы при сдвиге порога на единицу.

🔴 Служебный аккаунт площадки owner 2215 «comon» исключён везде: на него переписаны
чужие системы при чистке 2014 года, это не автор.

Текстовый вывод. Запуск: python comon_serial_authors.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "data"

MIN_TRADE_DAYS = 100          # фильтр измеримости — тот же, что в Блоках 2-4
MIN_ACTIVITY = 0.10
SERVICE_OWNERS = {2215}
CANDIDATES = [5, 8, 10, 11, 12, 15, 20, 21, 22, 25, 30]


def say(s=""):
    print(s, flush=True)


def head(t):
    say()
    say("=" * 92)
    say(t)
    say("=" * 92)


CHARTS = "--charts" in sys.argv


def chart_k_distribution(k, cutoff=10):
    """График 25: распределение числа созданных стратегий — границы не видно."""
    import comon_charts as ch

    f, ax = ch.fig()
    k = np.asarray(k, float)
    top = 60
    kk = np.arange(1, top + 1)
    cnt = np.array([(k == v).sum() for v in kk], float)
    tail = float((k > top).sum())
    ax.bar(kk, np.where(cnt > 0, cnt, np.nan), width=0.86, color=ch.BLUE,
           zorder=3, label="авторов с таким числом созданных стратегий")
    ax.plot([cutoff - 0.5, cutoff - 0.5], [0.5, 6000], color=ch.ORANGE, lw=2.0,
            ls="--", zorder=5,
            label=f"порог серийности, принятый в разделе: от {cutoff} стратегий")
    ax.set_yscale("log")
    ticks = (1, 3, 10, 30, 100, 300, 1000, 3000)
    ax.set_yticks(list(ticks))
    ax.set_yticklabels([ch.n_(v) for v in ticks])
    ax.set_ylim(0.6, 12000)
    ax.set_xlim(0, top + 1)
    ax.set_xlabel("сколько стратегий автор создал")
    ax.set_ylabel("авторов")
    ax.set_title("Границы между «попробовал» и «поток» в данных нет")
    ax.legend(loc="upper right", handlelength=2.4, labelspacing=0.55)
    gapless = 1
    while gapless < top and cnt[gapless] > 0:
        gapless += 1
    ch.note(ax,
            f"База — {ch.n_(len(k))} авторов и {ch.n_(int(k.sum()))} созданных "
            f"стратегий: вся популяция без служебного аккаунта площадки. Шкала "
            f"числа авторов логарифмическая, иначе видна только первая колонка. "
            f"За краем поля — {ch.n_(tail)} авторов с более чем {top} стратегиями.",
            f"Все значения от одной стратегии до {ch.n_(gapless)} представлены без "
            f"единого пропуска, и распределение спадает плавно. Значит любой порог "
            f"серийности — соглашение, и единственное честное — назвать его прямо "
            f"и показать, что выводы от него не зависят.")
    ch.save(f, 25, "created-per-author")
    print(f"    авторов {len(k)}, без пропусков до k={gapless}, "
          f"за краем {int(tail)}", flush=True)


def main():
    panel = pd.read_csv(DIR / "panel.csv.gz", low_memory=False)
    sh = pd.read_csv(DIR / "sharpe.csv.gz")[["id", "sharpe_ar", "activity"]]
    p = panel.merge(sh, on="id", how="left")
    p = p[p["owner_id"].notna() & ~p["owner_id"].isin(SERVICE_OWNERS)]

    p["ser"] = p["n_pts"] > 0
    p["msr"] = (p["n_trade"] >= MIN_TRADE_DAYS) & (p["activity"] >= MIN_ACTIVITY)
    p["alive"] = p["is_live"] == 1

    g = p.groupby("owner_id")
    a = pd.DataFrame({
        "k": g.size(),                       # СОЗДАНО — поведение, не исход
        "ser": g["ser"].sum(),
        "msr": g["msr"].sum(),
        "alive": g["alive"].sum(),
    })

    # ------------------------------------------------------------------ А ----
    head("А.  Сколько стратегий создаёт автор (вся популяция, служебный аккаунт исключён)")
    say(f"{'авторов':<44}{len(a):>10,}")
    say(f"{'систем':<44}{int(a['k'].sum()):>10,}")
    say()
    say("Перцентили числа созданных стратегий:")
    for q in (50, 75, 90, 95, 97, 98, 99, 99.5, 99.9):
        say(f"    p{q:<6} {a['k'].quantile(q / 100):>8.0f}")
    say(f"    {'макс':<7} {a['k'].max():>8.0f}")
    say()
    say("Доля авторов по числу созданных:")
    for lo, hi in ((1, 1), (2, 3), (4, 9), (10, 19), (20, 49), (50, 10**9)):
        m = a["k"].between(lo, hi)
        lab = f"{lo}" if lo == hi else (f"{lo}+" if hi > 10**8 else f"{lo}-{hi}")
        say(f"    {lab:<10}{int(m.sum()):>8,} авторов ({m.mean() * 100:>5.1f} %)"
            f"   {int(a.loc[m, 'k'].sum()):>7,} систем"
            f" ({a.loc[m, 'k'].sum() / a['k'].sum() * 100:>5.1f} %)")

    if CHARTS:
        say()
        say("── график 25 ────────────────────────────────────────────────────")
        chart_k_distribution(a["k"].to_numpy(float))
        say()

    # ------------------------------------------------------------------ Б ----
    head("Б.  Есть ли естественный разрыв в распределении")
    say("Ищем скачок: упорядочиваем авторов по k и смотрим, где сосед отстаёт заметно.")
    say("Если разрыва нет, распределение гладкое и порог придётся выбирать по другим")
    say("соображениям — это тоже результат, и его надо честно назвать.")
    say()
    top = a["k"].sort_values(ascending=False)
    vals = top.values
    say(f"{'позиция':>9}{'k':>7}{'разрыв до следующего':>24}")
    for i in range(min(40, len(vals) - 1)):
        gap = vals[i] - vals[i + 1]
        mark = "  <<< скачок" if gap >= 5 else ""
        say(f"{i + 1:>9}{vals[i]:>7}{gap:>24}{mark}")
    say()
    uniq = np.sort(a["k"].unique())
    holes = [(int(uniq[i]), int(uniq[i + 1])) for i in range(len(uniq) - 1)
             if uniq[i + 1] - uniq[i] > 1]
    say(f"Пропущенные значения k (ни у одного автора столько нет): {len(holes)} интервалов")
    say(f"    первые десять: {holes[:10]}")
    say(f"    наименьшее k, ниже которого пропусков НЕТ: {int(uniq[0])}"
        f" … {int(uniq[np.argmax(np.diff(uniq) > 1)]) if holes else int(uniq[-1])}")

    # ------------------------------------------------------------------ В ----
    head("В.  Пороги-кандидаты: что остаётся при каждом")
    say("«доля систем» — какую часть всей популяции держат отобранные авторы;")
    say("«верхних % авторов» — насколько узкой получается группа;")
    say("«медиана k» — типичный размер внутри группы (нужен для кластеризации).")
    say()
    hdr = (f'{"порог k >":<10}{"авторов":>9}{"верхних %":>11}{"систем":>9}'
           f'{"доля систем":>13}{"медиана k":>11}{"измеримых":>11}{"живых":>8}')
    say(hdr)
    say("-" * len(hdr))
    for c in CANDIDATES:
        s = a[a["k"] > c]
        if not len(s):
            continue
        say(f'{c:<10}{len(s):>9,}{len(s) / len(a) * 100:>10.2f}%{int(s["k"].sum()):>9,}'
            f'{s["k"].sum() / a["k"].sum() * 100:>12.1f}%{s["k"].median():>11.0f}'
            f'{int(s["msr"].sum()):>11,}{int(s["alive"].sum()):>8,}')

    # ------------------------------------------------------------------ Г ----
    head("Г.  Насколько выбор порога хрупок")
    say("Сколько авторов ДОБАВЛЯЕТСЯ при сдвиге порога на единицу вниз.")
    say("Если у порога стоит плотная толпа, выбор между «20» и «21» произволен —")
    say("именно этим плох нынешний раздел (GPMTrade с ровно 20 отсекался формулировкой).")
    say()
    say(f'{"порог k >":<12}{"авторов":>9}{"+ при сдвиге на 1 вниз":>26}')
    for c in CANDIDATES:
        n0 = int((a["k"] > c).sum())
        n1 = int((a["k"] > c - 1).sum())
        say(f'{c:<12}{n0:>9,}{n1 - n0:>26,}')

    say()
    say("готово")


if __name__ == "__main__":
    main()
