"""comon_data.py — проверка наличия первичных данных перед расчётом.

Часть скриптов считает по готовым наборам из data/ и работает сразу. Другой
части нужны первичные ряды — карточки стратегий и их дневная доходность,
которых в репозитории нет (почему — в DATA.md). Без этой проверки такой скрипт
падал бы где-то в середине с невнятным KeyError по пустой таблице, и понять из
него, что именно надо сделать, невозможно.
"""
import sys
from pathlib import Path

WHAT = {
    "profit": "дневные ряды доходности стратегий",
    "cards":  "карточки стратегий",
    "catalog": "выгрузка каталога витрины",
}


def require_raw(data_dir, *needed):
    """Остановиться с внятным объяснением, если первичных данных нет.

    data_dir — каталог data/ репозитория; needed — какие наборы нужны скрипту
    («profit», «cards», «catalog»). По умолчанию проверяются ряды и карточки.
    """
    needed = needed or ("profit", "cards")
    data_dir = Path(data_dir)
    missing = [n for n in needed
               if not (data_dir / n).is_dir() or not any((data_dir / n).iterdir())]
    if not missing:
        return

    script = Path(sys.argv[0]).name or "этот скрипт"
    print(f"\n{script}: не хватает первичных данных.\n", file=sys.stderr)
    for n in missing:
        print(f"  нет  data/{n}/   — {WHAT.get(n, n)}", file=sys.stderr)
    print(
        "\nЭтих данных в репозитории нет: каталог стратегий — база данных площадки,\n"
        "и выкладывать её копию мы не вправе (подробно — в DATA.md).\n"
        "\nЧто можно сделать:\n"
        "  1. Собрать данные заново — scripts/comon_fetch.js обращается к тем же\n"
        "     публичным страницам. Учтите: каталог живой, числа не совпадут с\n"
        "     опубликованными до последнего знака.\n"
        "  2. Запросить у автора точную копию выгрузки, на которой построена серия.\n"
        "  3. Запустить скрипты, которым сырьё не нужно: они считают по готовым\n"
        "     наборам из data/ и воспроизводят таблицы и графики серии.\n",
        file=sys.stderr)
    sys.exit(2)
