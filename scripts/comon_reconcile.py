"""comon_reconcile.py — сверка спорных чисел серии по панели.

Вычитка серии 2026-08-08 шла БЕЗ доступа к данным и оставила четыре расхождения,
которые нельзя разрешить чтением текстов. Здесь каждое считается прямо по панели.

  1.1  Стратегий, торговавших хотя бы день: 14 832 (главы 2, шесть мест) или
       14 833 (глава 1, приложение А2)? Арифметика спор усугубляет:
       19 978 − 5 145 не стартовавших = 14 833, но 13 395 смертей + 1 437 живых = 14 832.
  1.2  «1 437 живых стратегий с рядами» в разделе 1.3 — верное ли число и верная ли
       подпись? Проверяется не счётом, а ВОСПРОИЗВЕДЕНИЕМ ранговых корреляций витрины
       с пересчётом (ро = 0.954 по доходности, 1.000 по просадке): выборка та, на
       которой они получаются.
  1.3  Архив: 18 529 (таблица механизмов смерти, Б1) или 18 530 (весь остальной текст)?
       Ищем недостающую строку поимённо, а не объясняем разность словами.
  1.4  Дата среза: 4 или 5 августа? Ищем дату, на которую фактически зафиксированы
       is_live и последние точки рядов.
  1.5  Три клетки кросс-таблицы «механизм смерти x финансовый итог», читающиеся как
       противоречие (смерть у пика с убытком — 1 173, смерть у пика с разорением — 3,
       обычная просадка с разорением — 1). Пояснения под таблицей 2.3 выведены из
       логики классификации; здесь они проверяются по самим рядам.

Ничего не правит и не пишет: только печатает. Правки в тексты вносятся отдельно и
вручную, после того как числа показаны.

Текстовый вывод. Запуск: python comon_reconcile.py
"""
