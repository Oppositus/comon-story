def say(s=""):
    print(s, flush=True)


def head(t):
    say()
    say("=" * 78)
    say(t)
    say("=" * 78)


panel = pd.read_csv(DIR / "panel.csv.gz", low_memory=False)
deaths = pd.read_csv(DIR / "deaths.csv.gz")
say(f"панель {len(panel):,} строк · deaths {len(deaths):,} строк")

