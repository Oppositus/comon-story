head("Побочно: сколько «смертей у пика» опирается на вырожденно короткий ряд")

pk = deaths[deaths["mech"] == "смерть у пика"]
say(f"{'класс «смерть у пика» всего':<46}{len(pk):>8,}")
for lab, m in (("торговых дней = 1", pk["n_trade"] == 1),
               ("2-4", pk["n_trade"].between(2, 4)),
               ("5-19", pk["n_trade"].between(5, 19)),
               ("20-99", pk["n_trade"].between(20, 99)),
               ("100 и больше", pk["n_trade"] >= 100)):
    say(f"    {lab:<42}{m.sum():>8,}  ({m.mean() * 100:>5.1f} %)")
