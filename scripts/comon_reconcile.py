say()
ids = deaths[(deaths["mech"] == "смерть у пика") & (deaths["fin"] == "убыток")]["id"].tolist()
with Pool(8) as pool:
    res = [x for x in pool.map(curve, ids) if x]
a = pd.DataFrame(res, columns=["id", "n_trade", "eq_max", "eq_end"])
say(f"{'никогда не поднимались выше старта (max <= 1.0)':<50}"
    f"{(a['eq_max'] <= 1.0).sum():>6,}  ({(a['eq_max'] <= 1.0).mean() * 100:.1f} %)")
say(f"{'поднимались выше старта, но кончили ниже':<50}"
    f"{(a['eq_max'] > 1.0).sum():>6,}  ({(a['eq_max'] > 1.0).mean() * 100:.1f} %)")
say()
say("Насколько малы движения в этой клетке (старт = 1.00):")
say(f"{'':<22}{'5 %':>9}{'25 %':>9}{'медиана':>10}{'75 %':>9}{'95 %':>9}")
for lab, col in (("максимум кривой", "eq_max"), ("итог", "eq_end")):
    q = [a[col].quantile(x) for x in (0.05, 0.25, 0.5, 0.75, 0.95)]
    say(f"{lab:<22}" + "".join(f"{v:>9.4f}" for v in q[:3]) + "".join(f"{v:>9.4f}" for v in q[3:]))
say()
say("Торговых дней за жизнь в этой клетке:")
for lab, m in (("1", a["n_trade"] == 1), ("2-4", a["n_trade"].between(2, 4)),
               ("5-19", a["n_trade"].between(5, 19)), ("20-99", a["n_trade"].between(20, 99)),
               ("100 и больше", a["n_trade"] >= 100)):
    say(f"    {lab:<16}{m.sum():>6,}  ({m.mean() * 100:>5.1f} %)")
say()
say("ФАКТ: пояснение верно для 68 %, но не для всех — треть кривых старт превышала.")
say("Главное свойство клетки другое: это очень короткие жизни с мизерными потерями")
say("(медианный итог 0.9745, то есть -2.6 %), больше половины — не дольше четырёх дней.")

