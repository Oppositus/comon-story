say("стратегия восстановилась и умерла с прибылью. Финансовый итог берётся по худшей")
say("точке за всю жизнь, механизм — по последнему отрезку: отсюда сочетание.")

say()
say("--- Клетка «смерть у пика» x «убыток» (1 173 стратегии) ---")
