# ---------------------------------------------------------------- 1.1 --------
head("1.1  Сколько стратегий торговали хотя бы день (n_trade > 0)")

say("🔴 Ключ ко всем трём расхождениям — у is_live ТРИ состояния, а не два.")
say("Тексты серии молча считают «не живая» = «архивная», и на этом расходятся.")
say()
say(f"{'всего в панели':<46}{len(panel):>8,}")
say(f"{'  живых (is_live = 1)':<46}{live.sum():>8,}")
say(f"{'  архивных (is_live = 0)':<46}{arch.sum():>8,}")
say(f"{'  статус неизвестен (is_live пусто)':<46}{unk.sum():>8,}")
say(f"{'  сумма':<46}{live.sum() + arch.sum() + unk.sum():>8,}")
say()
say(f"{'торговали хотя бы день (n_trade > 0)':<46}{traded.sum():>8,}")
say(f"{'  из них живых':<46}{(traded & live).sum():>8,}")
say(f"{'  из них архивных':<46}{(traded & arch).sum():>8,}")
say(f"{'  из них с неизвестным статусом':<46}{(traded & unk).sum():>8,}")
say()
say(f"{'НЕ торговали ни дня (n_trade = 0)':<46}{(~traded).sum():>8,}")
say(f"{'  из них живых':<46}{((~traded) & live).sum():>8,}")
say(f"{'  из них архивных':<46}{((~traded) & arch).sum():>8,}")
say(f"{'  из них без единой точки ряда (n_pts = 0)':<46}{((~traded) & ~has_pts).sum():>8,}")
say(f"{'  из них ряд есть, но весь из нулей':<46}{((~traded) & has_pts).sum():>8,}")
say()
say("Два пути к числу, которые в текстах разошлись, — и оба верны, но про разное:")
say(f"  19 978 − не стартовавшие ({(~traded).sum():,}) = {len(panel) - (~traded).sum():,}"
    f"   ← ВСЕ торговавшие, включая строку с неизвестным статусом")
say(f"  смерти с торговлей ({(traded & arch).sum():,}) + живые с торговлей "
    f"({(traded & live).sum():,}) = {(traded & (live | arch)).sum():,}"
    f"   ← только с ИЗВЕСТНЫМ статусом")

# ---------------------------------------------------------------- 1.3 --------
head("1.3  Архив: 18 529 или 18 530 — какой строки нет в разборе смертей")

say(f"{'архивных (is_live = 0)':<46}{arch.sum():>8,}")
say(f"{'не живых (is_live != 1) — как считают тексты':<46}{(~live).sum():>8,}")
say(f"{'строк в deaths.csv.gz':<46}{len(deaths):>8,}")
say(f"{'множество deaths совпадает с is_live = 0':<46}"
    f"{str(set(deaths['id']) == set(panel.loc[arch, 'id'])):>8}")

miss = set(panel.loc[~live, "id"]) - set(deaths["id"])
extra = set(deaths["id"]) - set(panel.loc[~live, "id"])
say(f"{'не живых без строки в deaths':<46}{len(miss):>8,}")
say(f"{'строк deaths, которых нет среди не живых':<46}{len(extra):>8,}")

for sid in sorted(miss):
    r = panel[panel["id"] == sid].iloc[0]
    say()
    say(f"НЕДОСТАЮЩАЯ СТРОКА id={sid}")
    for c in ("has_card", "has_series", "owner_id", "created_at", "archived_at",
              "is_live", "n_pts", "n_trade", "first", "last", "last_trade",
              "tariff_id", "card_metrics_valid"):
        say(f"    {c:<22}{r[c]!r}")
    say()
    say(f"    Почему пустая: следы id={sid} в журнале выгрузки —")
    with open(DIR / "_log" / "fetch.log", encoding="utf-8", errors="replace") as f:
        for ln in f:
            if str(sid) in ln:
                say(f"      {ln.rstrip()}")

# ---------------------------------------------------------------- 1.2 --------
head("1.2  «1 437 живых стратегий с рядами» — какая выборка даёт ро 0.954 / 1.000")

say(f"{'живых всего':<46}{live.sum():>8,}")
say(f"{'  живых с рядом (n_pts > 0)':<46}{(live & has_pts).sum():>8,}")
say(f"{'  живых, торговавших хотя бы день':<46}{(live & traded).sum():>8,}")
say(f"{'  живых с card_metrics_valid':<46}{(live & (panel['card_metrics_valid'] == 1)).sum():>8,}")
say()
say("Ранговая корреляция «витрина против пересчёта из рядов» на разных выборках.")
say("card_annual — годовая доходность с карточки, cagr — расчёт из ряда;")
say("card_maxdd — просадка с карточки, maxdd — из ряда. Метод: Спирмен, попарное удаление NaN.")
say()
say(f"{'выборка':<42}{'n':>7}   {'ро доходность':<22}{'ро просадка'}")
say("-" * 94)

cands = [
    ("живые, ряд есть (n_pts > 0)", live & has_pts),
    ("живые, торговали хотя бы день", live & traded),
    ("живые, card_metrics_valid = 1", live & (panel["card_metrics_valid"] == 1)),
    ("живые, ряд есть и card_metrics_valid", live & has_pts & (panel["card_metrics_valid"] == 1)),
    ("живые, торговали и card_metrics_valid", live & traded & (panel["card_metrics_valid"] == 1)),
    ("все с рядом (живые и архивные)", has_pts),
]
for lab, m in cands:
    sub = panel[m]
    out = []
    for a, b in (("card_annual", "cagr"), ("card_maxdd", "maxdd")):
        d = sub[[a, b]].dropna()
        out.append(f"{stats.spearmanr(d[a], d[b]).statistic:.3f} (n={len(d):,})"
                   if len(d) > 2 else "нет данных")
    say(f"{lab:<42}{len(sub):>7,}   {out[0]:<22}{out[1]}")

say()
say("Целевые значения главы 1, раздел 1.3: 0.954 по доходности, 1.000 по просадке.")

# ---------------------------------------------------------------- 1.4 --------
head("1.4  Дата среза: на какой день фактически зафиксированы данные")

for c in ("last", "last_trade", "archived_at", "created_at"):
    s = panel[c].dropna().astype(str)
    say(f"{c:<14}min {s.min():<24} max {s.max()}")

say()
say("Последние дни рядов — сколько стратегий на каждой дате (хвост распределения):")
tail = panel.loc[has_pts, "last"].astype(str).value_counts().sort_index().tail(8)
for d, n in tail.items():
    say(f"    {d:<24}{n:>7,}")

say()
say("Живые: последние дни рядов (хвост):")
tail = panel.loc[live & has_pts, "last"].astype(str).value_counts().sort_index().tail(8)
for d, n in tail.items():
    say(f"    {d:<24}{n:>7,}")

say()
say("Журнал выгрузки (_log/fetch.log) — начало и конец:")
with open(DIR / "_log" / "fetch.log", encoding="utf-8", errors="replace") as f:
    lines = [ln.rstrip("\n") for ln in f if ln.strip()]
for ln in lines[:2] + ["    ..."] + lines[-2:]:
    say(f"    {ln}")

say()
say("Журнал загрузок (_log/state.ndjson) — первая и последняя метка:")
with gzip.open(DIR / "_log" / "state.ndjson", "rt") if str(
        DIR / "_log" / "state.ndjson").endswith(".gz") else open(
        DIR / "_log" / "state.ndjson", encoding="utf-8") as f:
    st = [ln for ln in f if ln.strip()]
say(f"    первая: {st[0].strip()[:120]}")
say(f"    последняя: {st[-1].strip()[:120]}")

# ---------------------------------------------------------------- 1.5 --------
head("1.5  Три спорные клетки таблицы «механизм x финансовый итог» — поштучно")

say("Пояснения под таблицей 2.3 выведены из ЛОГИКИ классификации, а не из самих")
say("стратегий. Здесь они проверяются по рядам. Классы задаются так (comon_death_class):")
say("  fin = разорение   <- maxDD <= -90 % ИЛИ итоговая эквити <= 0.1 (по ВСЕЙ жизни)")
say("  mech = смерть у пика <- падение от максимума до последнего дня не глубже 5 %")
say("  mech = обычная просадка <- ни бутстрап, ни тест разлома не сработали")


def load_r(sid):
    """Доходности торговых дней — тот же загрузчик, что в классификаторе смертей."""
    f = DIR / "profit" / f"{sid}.json.gz"
    if not f.exists():
        return np.array([])
    s = (json.loads(gzip.open(f, "rt").read()).get("data") or {}).get("strategy") or []
    r = np.array([float(x["rValue"] or 0.0) for x in s[::-1]])
    return r[r != 0.0]


def curve(sid):
    r = load_r(sid)
    if len(r) == 0:
        return None
    eq = np.cumprod(1.0 + r)
    return sid, len(r), float(eq.max()), float(eq[-1])


say()
say("--- Клетка «смерть у пика» x «разорение» (3 стратегии) ---")
say("Написано в тексте: «у трёх — обвал в начале ряда и плоский хвост».")
say()
three = deaths[(deaths["mech"] == "смерть у пика") & (deaths["fin"] == "разорение")]
say(f"{'id':>8}{'торг. дней':>12}{'итог':>10}{'maxDD':>9}{'n_hist':>8}"
    f"{'дней после пика':>17}   день обвала")
for _, r in three.iterrows():
    rr = load_r(int(r["id"]))
    day = f"{r['death_date']} ({rr[0]:.1%} за день)" if len(rr) else "ряд не прочитан"
    say(f"{int(r['id']):>8}{int(r['n_trade']):>12}{r['ret_total']:>9.1%}"
        f"{r['maxdd']:>9.1%}{int(r['n_hist']):>8}{int(r['len_final']):>17}   {day}")

say()
say("ФАКТ: у всех трёх ОДИН торговый день, на нём потеря 91-99.5 %. «Пик» у ряда из")
say("одной точки — она сама, поэтому падение от пика равно нулю и класс присвоен")
say("вырожденно. Это не «обвал и плоский хвост», а единственная сделка.")

say()
say("--- Клетка «обычная просадка» x «разорение» (1 стратегия) ---")
say("Написано в тексте: «история с провалами того же порядка».")
say()
one = deaths[(deaths["mech"] == "обычная просадка") & (deaths["fin"] == "разорение")]
for _, r in one.iterrows():
    sid = int(r["id"])
    rr = load_r(sid)
    eq = np.cumprod(1.0 + rr)
    say(f"    id                        {sid}")
    say(f"    торговых дней             {len(rr)}")
    say(f"    ИТОГ жизни                {r['ret_total']:+.1%}   <- закончила В ПЛЮСЕ")
    say(f"    максимальная просадка     {r['maxdd']:.1%}   <- отсюда «разорение»")
    say(f"    падение от пика до конца  {r['dd_final']:.1%}")
    say(f"    максимум кривой           {eq.max():.2f} (старт 1.00), минимум {eq.min():.2f}")
    say(f"    история до пика / после   {int(r['n_hist'])} / {int(r['len_final'])} дней")
say()
