say(f"{'пик пришёлся на первую же точку (n_hist = 1)':<46}{(pk['n_hist'] == 1).sum():>8,}")
say(f"{'после пика не было ни одного дня':<46}{(pk['len_final'] == 0).sum():>8,}")
say()
say("🔴 У стратегии с единственным торговым днём «смерть у пика» присваивается")
say("автоматически: падать от единственной точки некуда. Классу это не мешает —")
say("определение «умерла не дальше 5 % от максимума» само по себе корректно, — но")
say("доля вырожденных случаев в нём заметна и её стоит назвать в главе 2.")

say()
say("готово")
