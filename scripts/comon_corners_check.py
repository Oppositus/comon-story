"""comon_corners_check.py — насколько корректны «углы риск-доходности» из Блока 9 §9.10.3.

Замечание юзера 2026-08-09: у двух углов РАЗНЫЕ вторые условия — «тихие» отбираются
просадкой И Sharpe (качество), «агрессивные» — просадкой И доходностью. Значит один
угол по построению качественный, другой нет, и ставить их рядом как «две половины
спроса» может быть некорректно.

Проверяем четырьмя способами:
  1. что даёт СИММЕТРИЧНОЕ определение (только риск, без второго условия);
  2. что даёт ОДИНАКОВОЕ второе условие с обеих сторон (оба по Sharpe / оба по CAGR);
  3. устойчивость к порогам (они назначены, а не выведены);
  4. концентрация внутри угла — держится ли доля на нескольких системах (как в §9.10.4);
  5. 🔴 главное: достижим ли «тихий» угол выбором? Sharpe на витрине НЕ показывают,
     поэтому сегмент, определённый через Sharpe, не может быть выбором публики.
     Смотрим, что у этих систем стоит в ПОКАЗАННЫХ полях.

Текстовый вывод. Запуск: python comon_corners_check.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "data"


def say(s=""):
    print(s, flush=True)


def conc(w):
    """Концентрация подписок внутри группы: сколько систем держат половину, эфф. N, топ-1."""
    w = np.sort(np.asarray(w, float))[::-1]
    if w.sum() <= 0:
        return 0, 0.0, 0.0
    half = int(np.searchsorted(np.cumsum(w), w.sum() / 2) + 1)
    p = w / w.sum()
    return half, float(1 / (p ** 2).sum()), float(100 * p[0])


def main():
    p = pd.read_csv(DIR / "panel.csv.gz", low_memory=False)
    F = p[(p["is_live"] == 1) & p["sharpe"].notna()].copy()
    F["followers"] = F["followers"].fillna(0)
    S = F[F["followers"] > 0]          # только системы с подписчиками, как в §9.10.3
    tot = S["followers"].sum()
    say(f"база: {len(S)} живых систем с подписчиками, подписок {int(tot):,}")

    def row(lab, m):
        m = m.fillna(False)
        n, sub = int(m.sum()), float(S.loc[m, "followers"].sum())
        h, en, t1 = conc(S.loc[m, "followers"])
        say(f'{lab:<52} {n:>6} {sub:>9,.0f} {100*sub/tot:>7.1f}% {h:>8} {en:>7.1f} {t1:>6.1f}%')

    hdr = f'{"сегмент":<52} {"систем":>6} {"подписок":>9} {"доля":>8} {"полов.":>8} {"эфф.N":>7} {"топ-1":>7}'

    say()
    say("=" * 100)
    say("1. КАК СЕЙЧАС В ТЕКСТЕ (несимметрично: слева Sharpe, справа CAGR)")
    say("=" * 100)
    say(hdr); say("-" * len(hdr))
    row("тихие: просадка мельче −20 % И Sharpe ≥ 1", (S["maxdd"] > -0.20) & (S["sharpe"] >= 1))
    row("агрессивные: просадка глубже −50 % И CAGR ≥ 30 %", (S["maxdd"] < -0.50) & (S["cagr"] >= 0.30))

    say()
    say("=" * 100)
    say("2. СИММЕТРИЧНО: только риск, без второго условия вообще")
    say("=" * 100)
    say(hdr); say("-" * len(hdr))
    row("просадка мельче −20 %", S["maxdd"] > -0.20)
    row("просадка глубже −50 %", S["maxdd"] < -0.50)

    say()
    say("=" * 100)
    say("3. СИММЕТРИЧНО: одинаковое второе условие с обеих сторон")
    say("=" * 100)
    say(hdr); say("-" * len(hdr))
    row("тихие + Sharpe ≥ 1", (S["maxdd"] > -0.20) & (S["sharpe"] >= 1))
    row("агрессивные + Sharpe ≥ 1", (S["maxdd"] < -0.50) & (S["sharpe"] >= 1))
    say()
    row("тихие + CAGR ≥ 30 %", (S["maxdd"] > -0.20) & (S["cagr"] >= 0.30))
    row("агрессивные + CAGR ≥ 30 %", (S["maxdd"] < -0.50) & (S["cagr"] >= 0.30))

    say()
    say("=" * 100)
    say("4. УСТОЙЧИВОСТЬ К ПОРОГАМ (они назначены, а не выведены)")
    say("=" * 100)
    say(f'{"порог просадки для тихих":<28} {"доля подписок":>14}   |   '
        f'{"порог для агрессивных":<28} {"доля подписок":>14}')
    for a, b in ((-0.15, -0.40), (-0.20, -0.50), (-0.25, -0.60), (-0.30, -0.70)):
        ma = (S["maxdd"] > a) & (S["sharpe"] >= 1)
        mb = (S["maxdd"] < b) & (S["cagr"] >= 0.30)
        say(f'мельче {100*a:>5.0f} % и Sharpe ≥ 1  {100*S.loc[ma.fillna(False),"followers"].sum()/tot:>12.1f}%   |   '
            f'глубже {100*b:>5.0f} % и CAGR ≥ 30 % {100*S.loc[mb.fillna(False),"followers"].sum()/tot:>12.1f}%')

    say()
    say("=" * 100)
    say("5. 🔴 ДОСТИЖИМ ЛИ «ТИХИЙ» УГОЛ ВЫБОРОМ: что у этих систем в ПОКАЗАННЫХ полях")
    say("=" * 100)
    say("Sharpe на витрине не показывают вовсе — значит сегмент, заданный через Sharpe,")
    say("описывает исход, а не выбор. Смотрим, чем эти системы выделялись на витрине.")
    say()
    quiet = S[(S["maxdd"] > -0.20) & (S["sharpe"] >= 1)]
    aggr = S[(S["maxdd"] < -0.50) & (S["cagr"] >= 0.30)]
    say(f'{"величина (медианы)":<38} {"тихие":>10} {"агрессивные":>13} {"все с подписч.":>15}')
    for lab, col, mul, fmt in (
            ("витринная годовая доходность, %", "card_annual", 1, "{:.1f}"),
            ("витринная просадка, %", "card_maxdd", 1, "{:.1f}"),
            ("ярлык уровня риска (1-3)", "risk_level", 1, "{:.1f}"),
            ("рейтинг площадки", "rating", 1, "{:.2f}"),
            ("порог входа, тыс ₽", "min_sum", 1e-3, "{:.0f}"),
            ("возраст ряда, лет", "years", 1, "{:.1f}"),
            ("честный Sharpe", "sharpe", 1, "{:.2f}"),
            ("честный CAGR, %", "cagr", 100, "{:.1f}")):
        say(f'{lab:<38} {fmt.format(quiet[col].median()*mul):>10} '
            f'{fmt.format(aggr[col].median()*mul):>13} {fmt.format(S[col].median()*mul):>15}')

    say()
    say("Доля систем угла среди ВЕРХНЕЙ ТРЕТИ витрины по ПОКАЗАННОЙ доходности:")
    thr = S["card_annual"].quantile(2 / 3)
    for lab, d in (("тихие", quiet), ("агрессивные", aggr)):
        hi = (d["card_annual"] >= thr)
        say(f'  {lab:<14} {int(hi.sum()):>4} из {len(d):>4} ({100*hi.mean():>5.1f} %), '
            f'подписок в них {100*d.loc[hi,"followers"].sum()/d["followers"].sum():>5.1f} % угла')


if __name__ == "__main__":
    main()
