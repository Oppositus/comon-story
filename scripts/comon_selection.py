"""comon_selection.py — есть ли в автоследовании отбор: числа первого раздела заключения.

Вопрос раздела: по ту сторону витрины те же спекулянты, что и на общем рынке, или
площадка кого-то отбирает. Отвечаем с двух сторон:

  * КОНТРОЛЬНАЯ ГРУППА — Т-Инвестиции, маркетплейс той же модели, но с ЗАЯВЛЕННЫМ
    входным отбором («строгий отбор и проверка на доходность» — их справка). Если
    отбор производит мастеров, у отобранной площадки должен быть выше ПОТОЛОК;
  * ЭТА ПОПУЛЯЦИЯ — доля авторов с проверяемым результатом, посчитанная на базе,
    сопоставимой с внешними работами по спекулянтам (Тайвань: менее 1 % устойчиво
    прибыльных после издержек).

🔴 ПОЧЕМУ ПОТОЛОК, А НЕ МЕДИАНА. У Т нет кладбища: витрина показывает только живых,
и медиану это задирает неизвестно на сколько. Но невидимые стратегии могут быть
только ХУЖЕ показанных, поэтому наблюдаемый максимум — оценка истинного максимума
СНИЗУ. Потолок отсутствием кладбища не задирается, и сравнение потолков честно даже
при полностью невидимом архиве.

🔴 КОНВЕНЦИИ. sharpe = CAGR / волатильность (геометрический), sharpe_ar =
среднее / волатильность (арифметический, как в главе 3). t-статистика Sharpe —
формула Lo (2002) в том же виде, что у Comon в comon_sharpe_dist.py:

    t = S_ar * sqrt(лет) / sqrt(1 + S_ar^2 / 2)

Знаменатель штрафует высокий Sharpe (оценка тем неопределённее, чем она больше),
поэтому короткий ряд с эффектным Sharpe большого t не даёт. Короткий путь
`S * sqrt(лет)` без знаменателя НЕ ГОДИТСЯ — блок C печатает, насколько он врёт.

🔴 БАЗЫ. Comon: живые (is_live == 1), из них измеримые = не меньше 100 торговых дней
И активность (доля торговых дней в ряде) не ниже 10 %. Служебный аккаунт площадки
(owner 2215) исключён везде, где считаются авторы. Т: все 169 стратегий каталога.

Запуск: python comon_selection.py
"""
import numpy as np
import pandas as pd

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMON = ROOT / "data"
TINV = ROOT / "data" / "tinvest"

SERVICE_OWNER = 2215
MIN_TRADE_DAYS = 100
MIN_ACTIVITY = 0.10
MIN_YEARS_SKILL = 3            # длина истории для вердикта «умеет» (как в разделе 4.5)
EULER = 0.5772156649015329

BINS = [(0, 1.5, "до 1.5 года"), (1.5, 2.5, "1.5-2.5"),
        (2.5, 3.5, "2.5-3.5"), (3.5, 99, "больше 3.5")]


def say(s=""):
    print(s, flush=True)


def head(t):
    say()
    say("=" * 96)
    say(t)
    say("=" * 96)


def t_sharpe(s_ar, years):
    """t-статистика Sharpe по Lo (2002) — тот же расчёт, что у Comon в панели."""
    s = np.asarray(s_ar, dtype=float)
    y = np.asarray(years, dtype=float)
    return s * np.sqrt(np.maximum(y, 0)) / np.sqrt(1 + s * s / 2)


def emax(n):
    """E[max] n независимых стандартных нормальных — поправка на перебор (раздел 4.2)."""
    from scipy import stats
    n = max(float(n), 1.0 + 1e-9)
    return ((1 - EULER) * stats.norm.ppf(1 - 1 / n)
            + EULER * stats.norm.ppf(1 - 1 / (n * np.e)))


def load():
    panel = pd.read_csv(COMON / "panel.csv.gz", low_memory=False)
    panel["is_live"] = pd.to_numeric(panel["is_live"], errors="coerce")
    sh = (pd.read_csv(COMON / "sharpe.csv.gz")[["id", "sharpe_ar", "t_sharpe", "years"]]
          .rename(columns={"years": "sh_years", "sharpe_ar": "sh_ar",
                           "t_sharpe": "t_own"}))
    p = panel.merge(sh, on="id", how="left")
    p["activity"] = p["n_trade"] / p["n_pts"]
    p["msr"] = (p["n_trade"] >= MIN_TRADE_DAYS) & (p["activity"] >= MIN_ACTIVITY)
    live = p[p["is_live"] == 1].copy()
    t = pd.read_csv(TINV / "panel.csv.gz")
    t["t_sharpe"] = t_sharpe(t["sharpe_ar"], t["years"])
    return p, live, t


def main():
    p, live, t = load()
    meas = live[live["msr"]].copy()

    head("0. БАЗЫ И КОНТРОЛЬ (числа должны совпасть с интерлюдией)")
    say(f'{"Comon: живых стратегий":<52}{len(live):>10,}')
    say(f'{"Comon: из них измеримых (>=100 дней, активность >=10 %)":<52}{len(meas):>10,}')
    say(f'{"Т-Инвестиции: стратегий в каталоге":<52}{len(t):>10,}')
    say()
    say(f'{"медиана Sharpe (CAGR/вола): Comon":<52}{meas["sharpe"].median():>10.2f}')
    say(f'{"медиана Sharpe (CAGR/вола): Т":<52}{t["sharpe"].median():>10.2f}')
    say(f'{"медиана Sharpe арифм.: Comon":<52}{meas["sh_ar"].median():>10.2f}')
    say(f'{"медиана Sharpe арифм.: Т":<52}{t["sharpe_ar"].median():>10.2f}')
    say()
    say("Контроль: 1 262 / 169 и медианы 0.18 / 1.54 — строки интерлюдии.")

    # ---------------------------------------------------------------- A ----
    head("A. ПОТОЛОК: мера, устойчивая к отсутствию кладбища")
    say("Невидимые стратегии могут быть только хуже показанных, поэтому наблюдаемый")
    say("максимум — оценка истинного максимума СНИЗУ. Медиану отсутствие кладбища")
    say("задирает, потолок — нет. Если у отобранной площадки потолок не выше, отбор")
    say("мастеров не производит. Sharpe геометрический, расчёт из дневных рядов.")
    say()
    hdr = (f'{"возраст истории":<16}{"Т: n":>7}{"Т: мед.":>9}{"Т: p90":>9}{"Т: макс":>10}'
           f'{"C: n":>8}{"C: мед.":>9}{"C: p90":>9}{"C: макс":>10}')
    say(hdr)
    say("-" * len(hdr))
    for lo, hi, lab in BINS + [(0, 99, "Все")]:
        a = t[(t["years"] >= lo) & (t["years"] < hi)]["sharpe"].dropna()
        b = meas[(meas["years"] >= lo) & (meas["years"] < hi)]["sharpe"].dropna()
        say(f'{lab:<16}{len(a):>7}{a.median():>9.2f}{a.quantile(.9):>9.2f}{a.max():>10.2f}'
            f'{len(b):>8}{b.median():>9.2f}{b.quantile(.9):>9.2f}{b.max():>10.2f}')
    say()
    long_t = t[t["years"] >= 3.5]["sharpe"]
    long_c = meas[meas["years"] >= 3.5]["sharpe"]
    say(f'На сопоставимых по длине историях (больше 3.5 года) потолок Т {long_t.max():.2f} '
        f'против {long_c.max():.2f} у Comon —')
    say(f'выше он у НЕОТОБРАННОЙ площадки, причём на выборке в '
        f'{len(long_c) / len(long_t):.0f} раз большей.')
    say()
    say(f'⚠️ Старейшая стратегия Т: {t["years"].max():.2f} года. Пятилетних у Т ноль,')
    say(f'   у Comon живых измеримых с историей >= 5 лет: {int((meas["years"] >= 5).sum())}.')
    say("   Самую жёсткую проверку главы 3 (потолок 1.94 на пятилетних) на отобранной")
    say("   площадке провести НЕЛЬЗЯ — и это само по себе факт для раздела.")
    say()
    say("Контроль возраста карточки против длины ряда у Т (не обрезан ли ряд):")
    d = (t["age_years"] - t["years"]).dropna()
    say(f'   медиана разницы {d.median():+.2f} года, p10 {d.quantile(.1):+.2f}, '
        f'p90 {d.quantile(.9):+.2f} — API отдаёт полную историю, прорежённую до 300 точек.')

    # ---------------------------------------------------------------- B ----
    head("B. УСЕЧЕНИЕ: сколько стоит отбор, одним числом")
    say("Отрезаем у Comon верхушку и ищем, при каком отсечении его медиана равна")
    say("медиане Т. Ответ читается как «витрина Т выглядит как верхние X % Comon».")
    say()
    sets = (("все живые измеримые", meas["sharpe"].dropna(), t["sharpe"].dropna()),
            ("истории >= 3.5 года", meas[meas["years"] >= 3.5]["sharpe"].dropna(),
             t[t["years"] >= 3.5]["sharpe"].dropna()))
    tops = (50, 40, 35, 30, 25, 20, 15, 10)
    hdr = f'{"верхний хвост Comon":<24}' + "".join(f'{lab:>26}' for lab, _, _ in sets)
    say(hdr)
    say("-" * len(hdr))
    for tp in tops:
        row = f'топ {tp} %{"":<16}'[:24]
        for _, c, _ in sets:
            row += f'{c[c >= c.quantile(1 - tp / 100)].median():>26.2f}'
        say(row)
    row = f'{"МЕДИАНА Т (цель)":<24}'
    for _, _, a in sets:
        row += f'{a.median():>26.2f}'
    say(row)
    say(f'{"  n у Comon":<24}' + "".join(f'{len(c):>26,}' for _, c, _ in sets))
    say(f'{"  n у Т":<24}' + "".join(f'{len(a):>26,}' for _, _, a in sets))
    say()
    for lab, c, a in sets:
        tgt = a.median()
        best = min(tops, key=lambda x: abs(c[c >= c.quantile(1 - x / 100)].median() - tgt))
        say(f'   {lab}: медиана Т достигается отсечением топ-{best} % Comon')
    say()
    say("Отбор поднимает середину примерно на треть популяции и не трогает потолок.")

    # ---------------------------------------------------------------- C ----
    head("C. ДОЛЯ С ПРОВЕРЯЕМЫМ РЕЗУЛЬТАТОМ (расчёт 7) — мост к «менее 1 %» Тайваня")
    say("t-статистика Sharpe по Lo (2002): t = S*sqrt(лет)/sqrt(1 + S^2/2). Обе")
    say("площадки считаются одной формулой из своих же рядов.")
    say()
    say("🔴 Контроль формулы на Comon: пересчёт против колонки панели")
    chk = meas[["sh_ar", "sh_years", "t_own"]].dropna()
    rec = t_sharpe(chk["sh_ar"], chk["sh_years"])
    say(f'   максимальное расхождение {np.abs(rec - chk["t_own"]).max():.2e} — '
        f'формула та же самая.')
    say()
    say("🔴 Почему короткий путь S*sqrt(лет) без знаменателя брать нельзя:")
    naive = chk["sh_ar"] * np.sqrt(chk["sh_years"])
    say(f'   корреляция с честной t: {np.corrcoef(naive, chk["t_own"])[0, 1]:.3f}')
    say(f'   медиана отношения честная/наивная: {(chk["t_own"] / naive).median():.3f}')
    say(f'   доля t >= 2 у Comon: честная {100 * (chk["t_own"] >= 2).mean():.1f} % '
        f'против наивной {100 * (naive >= 2).mean():.1f} % — завышение вдвое.')
    say()
    hdr = (f'{"площадка":<34}{"n":>8}{"t >= 2":>16}{"t >= 3":>16}{"медиана t":>12}')
    say(hdr)
    say("-" * len(hdr))
    for lab, s, y in (("Comon, живые измеримые", meas["sh_ar"], meas["sh_years"]),
                      ("Т-Инвестиции, все 169", t["sharpe_ar"], t["years"])):
        v = pd.Series(t_sharpe(s, y)).dropna()
        say(f'{lab:<34}{len(v):>8,}'
            f'{f"{int((v >= 2).sum())} ({100 * (v >= 2).mean():.1f} %)":>16}'
            f'{f"{int((v >= 3).sum())} ({100 * (v >= 3).mean():.1f} %)":>16}'
            f'{v.median():>12.2f}')
    say()
    say("Контроль длины (t растёт с историей, у Т ряды короче — сравниваем внутри корзин):")
    hdr = f'{"возраст истории":<16}{"Т: n":>7}{"Т: t>=2":>12}{"Т: t>=3":>12}{"C: n":>8}{"C: t>=2":>12}{"C: t>=3":>12}'
    say(hdr)
    say("-" * len(hdr))
    for lo, hi, lab in BINS:
        a = pd.Series(t_sharpe(t["sharpe_ar"], t["years"]))[
            (t["years"] >= lo) & (t["years"] < hi)].dropna()
        b = pd.Series(t_sharpe(meas["sh_ar"].to_numpy(), meas["sh_years"].to_numpy()),
                      index=meas.index)[(meas["years"] >= lo) & (meas["years"] < hi)].dropna()
        say(f'{lab:<16}{len(a):>7}{f"{100 * (a >= 2).mean():.1f} %":>12}'
            f'{f"{100 * (a >= 3).mean():.1f} %":>12}{len(b):>8}'
            f'{f"{100 * (b >= 2).mean():.1f} %":>12}{f"{100 * (b >= 3).mean():.1f} %":>12}')
    say()
    say("⚠️ Дефляции на 169 сильно скоррелированных стратегиях Т не делали: она может")
    say("   только ОПУСТИТЬ числа Т, то есть против сделанного вывода не работает.")

    # ---------------------------------------------------------------- D ----
    head("D. АСИММЕТРИЯ ПЕРЕБОРА: почему архив мёртвых незаменим")
    c_auth = live[(live["n_pts"] > 0) & (live["owner_id"] != SERVICE_OWNER)]
    ca = c_auth["owner_id"].value_counts()
    ta = t["author_id"].value_counts()
    hdr = f'{"величина":<44}{"Т-Инвестиции":>16}{"Comon (живые)":>16}'
    say(hdr)
    say("-" * len(hdr))
    say(f'{"авторов":<44}{len(ta):>16,}{len(ca):>16,}')
    say(f'{"стратегий на витрине":<44}{len(t):>16,}{len(c_auth):>16,}')
    say(f'{"максимум стратегий у одного автора":<44}{int(ta.max()):>16,}{int(ca.max()):>16,}')
    say(f'{"медиана стратегий на автора":<44}{ta.median():>16.1f}{ca.median():>16.1f}')
    say(f'{"доля авторов ровно с одной стратегией":<44}'
        f'{f"{100 * (ta == 1).mean():.1f} %":>16}{f"{100 * (ca == 1).mean():.1f} %":>16}')
    say(f'{"доля авторов с 3 и более":<44}'
        f'{f"{100 * (ta >= 3).mean():.1f} %":>16}{f"{100 * (ca >= 3).mean():.1f} %":>16}')
    say()
    say("Типичный автор у Т ведёт БОЛЬШЕ стратегий, а не меньше. Значит премия за")
    say("перебор в его показанных числах структурно не меньше, чем у Comon, — но")
    say("оценить её у Т НЕЛЬЗЯ: отбракованные попытки не видны. У Comon она измерена")
    say("прямо (глава 4: 1.10 пункта Sharpe при 6-10 попытках), и измерима она только")
    say("потому, что площадка хранит архив.")

    # ---------------------------------------------------------------- 4 ----
    head("РАСЧЁТ 4. ДОЛЯ АВТОРОВ С ПРОВЕРЯЕМЫМ РЕЗУЛЬТАТОМ НА СОПОСТАВИМОЙ БАЗЕ")
    say("В главе 4 критерий «умеет торговать» применён к 235 СЕРИЙНЫМ авторам (10 и")
    say("больше созданных стратегий) и дал 23. Сравнивать это с «менее 1 % устойчиво")
    say("прибыльных» у Barber и др. по Тайваню нельзя: там знаменатель — все, кто")
    say("пробовал. Здесь тот же критерий считается на всей популяции авторов.")
    say()
    say("Критерий (задан в главе 4, не меняется): |t| >= 2 И арифметический Sharpe >= 1.0")
    say(f'И Sharpe выше поправки на перебор E[max](k)/sqrt(лет) И история >= {MIN_YEARS_SKILL} лет;')
    say("плюс условие на автора: медианный Sharpe его измеримых систем >= 0.")
    say()
    a = p[p["owner_id"].notna() & (p["owner_id"] != SERVICE_OWNER)].copy()
    k = a.groupby("owner_id").size().rename("k")
    s = a[a["msr"]].merge(k, left_on="owner_id", right_index=True, how="left").copy()
    s = s[s["sh_ar"].notna() & s["sh_years"].notna()]
    s["thr"] = [emax(kk) / np.sqrt(max(y, 1e-9)) for kk, y in zip(s["k"], s["sh_years"])]
    s["ok"] = ((s["t_own"].abs() >= 2) & (s["sh_ar"] >= 1.0)
               & (s["sh_ar"] > s["thr"]) & (s["sh_years"] >= MIN_YEARS_SKILL))
    med = s.groupby("owner_id")["sh_ar"].median()
    win = s[s["ok"]].groupby("owner_id").size()
    skilled = {o for o in win.index if med.get(o, -9) >= 0}
    say(f'{"измеримых систем у всех авторов":<52}{len(s):>10,}')
    say(f'{"  прошли критерий систем":<52}{int(s["ok"].sum()):>10,}')
    say(f'{"  авторов хотя бы с одной такой системой":<52}{len(win):>10,}')
    say(f'{"  из них с медианным Sharpe >= 0 — УМЕЮЩИЕ":<52}{len(skilled):>10,}')
    say()
    say("Доля умеющих на разных знаменателях — лестница от самой широкой базы к узкой:")
    say()
    bases = (("все авторы площадки за её историю", a["owner_id"].nunique()),
             ("  из них: хотя бы одна стратегия с рядом",
              a[a["n_pts"] > 0]["owner_id"].nunique()),
             ("  из них: хотя бы одна торговавшая",
              a[a["n_trade"] > 0]["owner_id"].nunique()),
             ("  из них: хотя бы одна измеримая", s["owner_id"].nunique()),
             ("серийные авторы (10 и больше созданных) — глава 4",
              int((k >= 10).sum())))
    hdr = f'{"знаменатель":<52}{"авторов":>10}{"умеющих":>10}{"доля":>10}'
    say(hdr)
    say("-" * len(hdr))
    for lab, n in bases:
        if lab.startswith("серийные"):
            m = len({o for o in skilled if k.get(o, 0) >= 10})
        else:
            m = len(skilled)
        say(f'{lab:<52}{n:>10,}{m:>10,}{f"{100 * m / n:.2f} %":>10}')
    say()
    say("🔴 Как это читать. Верхняя строка — знаменатель, ближайший по смыслу к")
    say("внешним работам: все, кто вообще попробовал публично торговать на площадке.")
    say("Нижняя — база главы 4, где отбор по числу попыток уже произошёл.")
    say()
    say("Сверка с главой 4: серийных авторов должно быть 235, умеющих среди них 23.")

    say()
    say("готово")


if __name__ == "__main__":
    main()
